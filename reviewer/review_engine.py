"""
Review engine for the GPT-Based Code Review System.

generate_review(code, language) is the single entry point used by views.py.
It returns a dict: {"feedback": str, "score": int, "issues_found": int, "engine": "gpt"|"heuristic"}

If settings.OPENAI_API_KEY is configured, the review is generated by calling
the OpenAI Chat Completions API with a prompt engineered for accurate,
constructive programming-education feedback. If no key is configured (the
default, so the project works out of the box with no external setup), a
built-in static-analysis engine produces the review instead.
"""

import re
import json
import requests
from django.conf import settings


REVIEW_SYSTEM_PROMPT = (
    "You are an expert programming instructor reviewing a student's code "
    "submission for a programming education platform. Review the code for "
    "correctness, style, readability, efficiency, and best practices. "
    "Be specific and reference line numbers or code snippets where relevant. "
    "Respond ONLY with valid JSON in this exact shape: "
    '{"score": <0-100 integer>, "issues_found": <integer>, "feedback": '
    '"<markdown-formatted feedback with sections: Summary, Strengths, '
    'Issues & Suggestions, Overall Score>"}'
)


def _call_openai(code: str, language: str) -> dict:
    headers = {
        "Authorization": f"Bearer {settings.OPENAI_API_KEY}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": settings.OPENAI_MODEL,
        "messages": [
            {"role": "system", "content": REVIEW_SYSTEM_PROMPT},
            {
                "role": "user",
                "content": f"Language: {language}\n\nCode:\n```{language}\n{code}\n```",
            },
        ],
        "temperature": 0.3,
    }
    response = requests.post(
        "https://api.openai.com/v1/chat/completions",
        headers=headers,
        json=payload,
        timeout=30,
    )
    response.raise_for_status()
    content = response.json()["choices"][0]["message"]["content"]
    content = content.strip().removeprefix("```json").removeprefix("```").removesuffix("```").strip()
    data = json.loads(content)
    return {
        "feedback": data.get("feedback", "No feedback returned."),
        "score": int(data.get("score", 50)),
        "issues_found": int(data.get("issues_found", 0)),
        "engine": "gpt",
    }


# ---------------------------------------------------------------------------
# Heuristic / static-analysis fallback engine
# ---------------------------------------------------------------------------

def _heuristic_review(code: str, language: str) -> dict:
    issues = []
    lines = code.splitlines()

    for i, line in enumerate(lines, start=1):
        if len(line) > 100:
            issues.append(f"Line {i}: line exceeds 100 characters — consider wrapping it.")
        if re.search(r"\bTODO\b|\bFIXME\b", line):
            issues.append(f"Line {i}: unresolved TODO/FIXME comment.")
        if re.search(r"except\s*:\s*$", line):
            issues.append(f"Line {i}: bare 'except:' clause catches everything — catch specific exceptions.")
        if re.search(r"""(password|secret|api_key|token)\s*=\s*['"][^'"]+['"]""", line, re.I):
            issues.append(f"Line {i}: possible hardcoded credential/secret — move to environment variables.")
        if language == "python" and re.match(r"^\s*print\(", line):
            issues.append(f"Line {i}: 'print' statement found — use logging in production code.")
        if "\t" in line:
            issues.append(f"Line {i}: mixed tabs used for indentation — prefer spaces for consistency.")

    if language == "python":
        if "def " in code and '"""' not in code and "'''" not in code:
            issues.append("No docstrings found — consider documenting functions for clarity.")
        if re.search(r"import \*", code):
            issues.append("Wildcard import ('import *') found — import only what you need.")

    long_functions = re.findall(r"def\s+\w+\([^)]*\):((?:\n(?: {4}|\t).*)*)", code)
    for body in long_functions:
        if len(body.splitlines()) > 40:
            issues.append("A function body exceeds 40 lines — consider breaking it into smaller functions.")

    if not code.strip():
        issues.append("Submission is empty.")

    issue_count = len(issues)
    score = max(0, 100 - issue_count * 8)

    strengths = []
    if issue_count == 0:
        strengths.append("No obvious style or safety issues detected — clean submission.")
    if len(lines) > 0 and issue_count < len(lines) / 10:
        strengths.append("Overall structure is reasonably clean relative to code length.")
    if not strengths:
        strengths.append("Code compiles conceptually and follows a recognizable structure.")

    feedback_lines = [
        "## Summary",
        f"Automated static-analysis review of this {dict(_LANG_LABELS).get(language, language)} submission "
        f"({len(lines)} lines).",
        "",
        "## Strengths",
    ]
    feedback_lines += [f"- {s}" for s in strengths]
    feedback_lines += ["", "## Issues & Suggestions"]
    if issues:
        feedback_lines += [f"- {issue}" for issue in issues[:15]]
        if len(issues) > 15:
            feedback_lines.append(f"- ...and {len(issues) - 15} more issue(s).")
    else:
        feedback_lines.append("- No issues detected by static analysis.")
    feedback_lines += ["", f"## Overall Score: {score}/100"]

    return {
        "feedback": "\n".join(feedback_lines),
        "score": score,
        "issues_found": issue_count,
        "engine": "heuristic",
    }


_LANG_LABELS = [
    ("python", "Python"), ("java", "Java"), ("c", "C"),
    ("cpp", "C++"), ("javascript", "JavaScript"), ("other", "code"),
]


def generate_review(code: str, language: str) -> dict:
    if getattr(settings, "OPENAI_API_KEY", ""):
        try:
            return _call_openai(code, language)
        except Exception:
            # Fall back gracefully if the API call fails for any reason
            # (network, quota, invalid key, malformed response, etc.)
            result = _heuristic_review(code, language)
            result["feedback"] = (
                "_Note: GPT review temporarily unavailable, showing static analysis instead._\n\n"
                + result["feedback"]
            )
            return result
    return _heuristic_review(code, language)
